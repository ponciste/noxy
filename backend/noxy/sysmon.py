"""Sysmon for Linux file-creation events (Event ID 11), read from the rsyslog file `setup sysmon` configures.

Each event is one syslog line carrying Sysmon's XML. Filenames come from the sample, so the line is treated as
hostile: no XML parser (no entity or DTD handling at all), only bounded regular expressions over the escaped text,
then the five standard XML entities are decoded. Lines are capped in length and count.
"""
import datetime as dt
import gzip
import os
import re
from pathlib import Path

from . import util

LOG = Path(os.environ.get("NOXY_SYSMON_LOG") or "/var/log/noxy/sysmon.log")
CONFIG = Path("/etc/noxy/sysmon.xml")
MAX_LINE = 16384
MAX_EVENTS = 200000
EVENT_ID = re.compile(r"<EventID>(\d+)</EventID>")
DATA = re.compile(r'<Data Name="(\w{1,40})">([^<]{0,4096})</Data>')
ENTITIES = (("&lt;", "<"), ("&gt;", ">"), ("&quot;", '"'), ("&apos;", "'"), ("&amp;", "&"))

# Where a sample (or something you trigger) can leave a file worth seeing. Watching every path floods journald on
# a desktop, so Sysmon looks only here and skips the caches that churn all day. auditd still covers executions,
# connections and the persistence paths in its rules wherever they are.
WATCHED = ("/home/", "/root/", "/tmp/", "/var/tmp/", "/dev/shm/", "/etc/", "/opt/", "/usr/local/", "/srv/",
           "/var/spool/cron/", "/usr/lib/systemd/", "/var/www/")
SKIPPED_PREFIX = ("/dev/shm/org.mozilla", "/dev/shm/org.chromium", "/dev/shm/.org.chromium", "/tmp/.X11-unix/",
                  "/tmp/.ICE-unix/", "/tmp/systemd-private-", "/etc/ld.so.cache")
SKIPPED_CONTAINS = ("/.cache/mozilla/", "/.mozilla/firefox/", "/snap/firefox/common/", "/.cache/tracker3/",
                    "/.cache/thumbnails/", "/.cache/fontconfig/", "/.cache/mesa_shader_cache/", "/.cache/gstreamer-1.0/",
                    "/.cache/ibus/", "/.cache/chromium/", "/.config/chromium/", "/.cache/google-chrome/",
                    "/.config/Code/Cache", "/.config/Code/CachedData/", "/.config/Code/logs/", "/.config/Code/User/workspaceStorage/",
                    "/.config/Code/User/globalStorage/", "/.config/Code/Service Worker/", "/.config/Code/blob_storage/",
                    "/.config/Code/GPUCache/", "/.config/Code/Code Cache/", "/.local/share/gvfs-metadata/",
                    "/.local/share/tracker/", "/.config/dconf/", "/.config/pulse/", "/.local/state/wireplumber/",
                    "/.config/sublime-text/Local/", "/.cache/sublime-text/")


def _xml_escape(v):
    return v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def config_xml():
    inc = "\n".join(f'        <TargetFilename condition="begin with">{_xml_escape(p)}</TargetFilename>' for p in WATCHED)
    exc = "\n".join([f'        <TargetFilename condition="begin with">{_xml_escape(p)}</TargetFilename>' for p in SKIPPED_PREFIX]
                    + [f'        <TargetFilename condition="contains">{_xml_escape(p)}</TargetFilename>' for p in SKIPPED_CONTAINS])
    return f"""<!-- Generated by noxy setup sysmon. File creation only: auditd already covers executions and connections. -->
<!-- Watched: home folders, temp folders, /etc, /opt, /usr/local, cron and systemd units. Browser, desktop and -->
<!-- editor caches are skipped at the source, because a desktop writes thousands of them an hour. -->
<Sysmon schemaversion="4.81">
  <EventFiltering>
    <RuleGroup name="" groupRelation="or">
      <ProcessCreate onmatch="include"/>
      <NetworkConnect onmatch="include"/>
      <ProcessTerminate onmatch="include"/>
      <RawAccessRead onmatch="include"/>
      <ProcessAccess onmatch="include"/>
      <FileDelete onmatch="include"/>
      <FileCreate onmatch="include">
{inc}
      </FileCreate>
    </RuleGroup>
    <RuleGroup name="" groupRelation="or">
      <FileCreate onmatch="exclude">
{exc}
      </FileCreate>
    </RuleGroup>
  </EventFiltering>
</Sysmon>
"""


CONFIG_XML = config_xml()


def _unescape(v):
    for a, b in ENTITIES:
        v = v.replace(a, b)
    return v


def _utc(v):
    try:
        return dt.datetime.strptime(v[:26], "%Y-%m-%d %H:%M:%S.%f").replace(tzinfo=util.UTC).timestamp()
    except ValueError:
        try:
            return dt.datetime.strptime(v[:19], "%Y-%m-%d %H:%M:%S").replace(tzinfo=util.UTC).timestamp()
        except ValueError:
            return None


def parse_line(line):
    """One syslog line -> file-creation dict, or None for anything else."""
    if len(line) > MAX_LINE or "<EventID>11</EventID>" not in line:
        return None
    m = EVENT_ID.search(line)
    if not m or m.group(1) != "11":
        return None
    d = {k: _unescape(v) for k, v in DATA.findall(line)}
    path = d.get("TargetFilename")
    ts = _utc(d.get("UtcTime") or d.get("CreationUtcTime") or "")
    if not path or ts is None:
        return None
    try:
        pid = int(d.get("ProcessId") or 0)
    except ValueError:
        pid = 0
    return {"ts": ts, "pid": pid, "image": util.safe_text(d.get("Image") or "", 400),
            "path": util.safe_text(path, 1000), "user": util.safe_text(d.get("User") or "", 64)}


def log_files(path=None):
    """The log and its rotations (sysmon.log.1, .2, optionally .gz), oldest first."""
    p = Path(path or LOG)
    out = []
    try:
        for f in p.parent.glob(p.name + "*"):
            m = re.fullmatch(re.escape(p.name) + r"(?:\.(\d+))?(\.gz)?", f.name)
            if m and f.is_file() and not f.is_symlink():
                out.append((int(m.group(1) or 0), f))
    except OSError:
        return []
    return [f for _, f in sorted(out, reverse=True)]


def _open(f):
    return gzip.open(f, "rt", errors="replace") if f.suffix == ".gz" else open(f, errors="replace")


def parse(files, since, until=None):
    """File-creation events in [since, until]. Files last written before `since` are skipped unread."""
    out, earliest = [], None
    for f in files:
        try:
            if f.stat().st_mtime < since - 60:
                continue
            with _open(f) as fh:
                for line in fh:
                    ev = parse_line(line)
                    if not ev:
                        continue
                    if earliest is None or ev["ts"] < earliest:
                        earliest = ev["ts"]
                    if ev["ts"] < since or (until and ev["ts"] > until):
                        continue
                    out.append(ev)
                    if len(out) >= MAX_EVENTS:
                        return out, earliest, True
        except OSError as e:
            if isinstance(e, PermissionError):
                raise
            continue
    return out, earliest, False


def earliest_event(files):
    for f in files:
        try:
            with _open(f) as fh:
                for line in fh:
                    ev = parse_line(line)
                    if ev:
                        return ev["ts"]
        except OSError:
            continue
    return None


def running(procs):
    """procs: [(pid, comm, cmdline)] from status._procs()."""
    return any(comm == "sysmon" or cmd.startswith(("/opt/sysmon/sysmon", "/usr/bin/sysmon")) for _, comm, cmd in procs)
